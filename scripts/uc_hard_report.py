def jl(p):
    return [json.loads(x) for x in open(p)]


def slack(r):
    return (r.get("shed") or 0) + (r.get("short") or 0)


def first_reach(inc, target):
    for t, o, *_ in inc:
        if o <= target * (1 + 1e-9) + 1e-9:
            return float(t)
    return np.nan


def lp_stats(d, sysm):
    from otsl.fixpolicy import align_to_prediction
    c, lp, db = d["obj"], d["c_rel"], d["bound"]
    g = (c - lp) / c * 100
    gd = (db - lp) / db * 100
    u = d["u_rel"]
    integ = np.minimum(u, 1 - u) <= 1e-6
    wrong, frac = [], []
    for i in range(len(c)):
        r = (u[i] > 0.5).astype(np.int8)
        ua = align_to_prediction(sysm, d["u"][i], r, d["u0"][i])
        wrong.append(int(((ua != r) & integ[i]).sum()))
        frac.append(int((~integ[i]).sum()))
    t = d["time"]
    return dict(n=len(c), gap_c_mean=float(g.mean()), gap_c_median=float(np.median(g)), gap_c_p90=float(np.percentile(g, 90)),
                gap_c_max=float(g.max()), gap_db_mean=float(gd.mean()), gap_db_median=float(np.median(gd)),
                gap_db_max=float(gd.max()), integral=float(integ.mean() * 100), frac_per_inst=float(np.mean(frac)),
                wrong_int_per_inst=float(np.mean(wrong)), wrong_int_median=float(np.median(wrong)),
                milp_time_mean=float(t.mean()), milp_time_median=float(np.median(t)), milp_time_max=float(t.max()),
                milp_opt=int(d["opt"].sum()), served=float(np.mean((d["shed"] + d["short"]) < 1e-6) * 100),
                c_blk_gap_median=float(np.median((d["c_blk"] - c) / c * 100)))


