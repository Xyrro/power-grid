def test_tables(recs, te, out):
    by = {}
    for r in recs:
        by.setdefault((r["rule"], r["mip_rel_gap"]), {})[r["i"]] = r
    ref = by[("full MILP", 1e-3)]
    keys = [k for k in by if all(i in by[k] for i in ref)]
    idx = sorted(i for i in ref if all(i in by[k] for k in keys))
    n = len(idx)
    DB = np.array([ref[i]["bound"] for i in idx])
    t_ref = np.array([ref[i]["time"] for i in idx])
    order = [("full MILP", 1e-3), ("full MILP", 5e-3), ("full MILP", 1e-2)] + sorted(
        [k for k in keys if k[0] != "full MILP"], key=lambda k: (RULES.index(k[0]) if k[0] in RULES else 9, k[1]))
    X = {}
    for k in order:
        R = by[k]
        feas = np.array([bool(R[i]["feasible"]) for i in idx])
        cost = np.array([R[i]["obj"] if R[i]["feasible"] else np.nan for i in idx], float)
        tm = np.array([R[i]["time"] + R[i].get("pre_s", 0) + R[i].get("relax_s", 0) + R[i].get("guard_s", 0) for i in idx])
        gap = (cost - DB) / cost * 100
        sp = t_ref / tm
        served = np.array([R[i]["feasible"] and slack(R[i]) < 1e-6 for i in idx])
        ttq = np.array([min(first_reach(ref[i]["inc"], cost[q]) if feas[q] else np.nan, t_ref[q]) if feas[q] else np.nan
                        for q, i in enumerate(idx)])
        ttq = np.where(np.isnan(ttq) & feas, t_ref, ttq)
        X[k] = dict(feas=feas, gap=gap, sp=sp, tm=tm, served=served, fixed=np.array([R[i].get("fixed_share", 0) for i in idx]) * 100,
                    ttq_sp=ttq / tm)
    ret = np.array([ref[i]["time"] for i in idx]) / te["time"][idx]
    same = np.mean([abs(ref[i]["obj"] - te["obj"][i]) <= 1e-6 * abs(te["obj"][i]) for i in idx]) * 100
    L = ["", f"## Test ({n} instances; every run of an instance back to back in one single-threaded process, cores 2 and 3)", "",
         f"Reference: the full MILP at 0.1 % re-timed in the evaluation process; vs the data-generation run of the same "
         f"instance: time ratio median {np.median(ret):.2f} ({np.mean(np.abs(ret - 1) <= 0.1) * 100:.0f} % within 10 %), same "
         f"objective on {same:.0f} %. Mean T_ref {t_ref.mean():.1f} s (median {np.median(t_ref):.1f} s). Method time includes "
         "the LP relaxation (if used), inference, thresholding and guards.", "",
         "| rule | mip_rel_gap | feasible % | gap mean % [95 % CI] | median | max | speed-up mean [95 % CI] | median | geo. mean | "
         "ratio of means | time to the same quality: median / geo. mean | fixed % | served % |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    out["test"] = dict(n=n, timing=dict(ratio_median=float(np.median(ret)), within10=float(np.mean(np.abs(ret - 1) <= 0.1) * 100),
                                        same_obj=float(same), t_ref_mean=float(t_ref.mean())), rows={}, paired={})
    gm = lambda x: float(np.exp(np.mean(np.log(x))))
    for k in order:
        x = X[k]
        f = x["feas"]
        g, sp = x["gap"][f], x["sp"][f]
        st = dict(feasible=float(f.mean() * 100), gap_mean=float(g.mean()), gap_ci=boot_ci(g), gap_median=float(np.median(g)),
                  gap_max=float(g.max()), sp_mean=float(sp.mean()), sp_ci=boot_ci(sp), sp_median=float(np.median(sp)),
                  sp_geo=gm(sp), sp_ratio=float(t_ref[f].mean() / x["tm"][f].mean()), ttq_median=float(np.median(x["ttq_sp"][f])),
                  ttq_geo=gm(x["ttq_sp"][f]), fixed=float(x["fixed"][f].mean()), served=float(x["served"].mean() * 100))
        out["test"]["rows"][f"{k[0]} @ {k[1] * 100:g}%"] = st
        L.append(f"| {k[0]} | {k[1] * 100:g} % | {st['feasible']:.0f} | {st['gap_mean']:.2f} [{st['gap_ci'][0]:.2f}, {st['gap_ci'][1]:.2f}] | "
                 f"{st['gap_median']:.2f} | {st['gap_max']:.2f} | {st['sp_mean']:.1f} [{st['sp_ci'][0]:.1f}, {st['sp_ci'][1]:.1f}] | "
                 f"{st['sp_median']:.1f} | {st['sp_geo']:.1f} | {st['sp_ratio']:.1f} | {st['ttq_median']:.1f} / {st['ttq_geo']:.1f} | "
                 f"{st['fixed']:.1f} | {st['served']:.0f} |")
    L += ["", "Paired differences (row − reference, instances both solve; bootstrap 95 % CI). Time ratio = geometric mean of "
          "T_reference / T_row (> 1: the row is faster).", "",
          "| row | reference | n | Δ gap pp [CI] | Δ log speed-up [CI] | time ratio | row better / reference better (gap > 0.01 pp) |",
          "|---|---|---|---|---|---|---|"]
    pairs = []
    for k in order:
        if k[0] != "full MILP":
            pairs.append((k, ("full MILP", k[1])))
    pipe = [k for k in order if k[0] == "pipeline"]
    for kp in pipe:
        for k in order:
            if k[0] not in ("full MILP", "pipeline") and k[1] == kp[1]:
                pairs.append((kp, k))
        for g in (5e-3, 1e-2):
            pairs.append((kp, ("full MILP", g)))
    for a, b in pairs:
        if a not in X or b not in X:
            continue
        both = X[a]["feas"] & X[b]["feas"]
        dg = (X[a]["gap"] - X[b]["gap"])[both]
        dl = (np.log(X[a]["sp"]) - np.log(X[b]["sp"]))[both]
        p = dict(n=int(both.sum()), d_gap=float(dg.mean()), d_gap_ci=boot_ci(dg), d_log=float(dl.mean()), d_log_ci=boot_ci(dl),
                 ratio=float(np.exp(dl.mean())), a_better=int((dg < -0.01).sum()), b_better=int((dg > 0.01).sum()))
        nm = lambda k: f"{k[0]} @ {k[1] * 100:g}%"
        out["test"]["paired"][f"{nm(a)} vs {nm(b)}"] = p
        L.append(f"| {nm(a)} | {nm(b)} | {p['n']} | {p['d_gap']:+.3f} [{p['d_gap_ci'][0]:+.3f}, {p['d_gap_ci'][1]:+.3f}] | "
                 f"{p['d_log']:+.2f} [{p['d_log_ci'][0]:+.2f}, {p['d_log_ci'][1]:+.2f}] | {p['ratio']:.2f}× | "
                 f"{p['a_better']} / {p['b_better']} |")
    # where the LP relaxation is weak: test instances split at the median LP gap to the reference dual bound
    lpg = np.array([(DB[q] - te["c_rel"][i]) / DB[q] * 100 for q, i in enumerate(idx)])
    hi = lpg > np.median(lpg)
    L += ["", f"By LP-relaxation gap (test instances split at the median LP gap to DB, {np.median(lpg):.2f} %): mean gap % "
          "(feasible instances) and geometric-mean speed-up of each rule; and the learned pipeline minus the LP pipeline at "
          "0.5 % (Δ gap pp and Δ log speed-up [95 % CI]).", "",
          "| rule | mip_rel_gap | weak half: gap % | speed-up | strong half: gap % | speed-up |", "|---|---|---|---|---|---|"]
    out["test"]["by_lp_gap"] = dict(median_lp_gap=float(np.median(lpg)), rows={})
    gm = lambda x: float(np.exp(np.mean(np.log(x)))) if len(x) else np.nan
    for k in order:
        x = X[k]
        row = {}
        for nm_, msk in (("weak", hi), ("strong", ~hi)):
            f = x["feas"] & msk
            row[nm_] = dict(gap=float(x["gap"][f].mean()), sp_geo=gm(x["sp"][f]), n=int(f.sum()), n_all=int(msk.sum()))
        out["test"]["by_lp_gap"]["rows"][f"{k[0]} @ {k[1] * 100:g}%"] = row
        L.append(f"| {k[0]} | {k[1] * 100:g} % | {row['weak']['gap']:.2f} | {row['weak']['sp_geo']:.1f} | "
                 f"{row['strong']['gap']:.2f} | {row['strong']['sp_geo']:.1f} |")
    a, b = ("pipeline", 5e-3), ("LP pipeline", 5e-3)
    if a in X and b in X:
        for nm_, msk in (("weak half", hi), ("strong half", ~hi)):
            both = X[a]["feas"] & X[b]["feas"] & msk
            dg = (X[a]["gap"] - X[b]["gap"])[both]
            dl = (np.log(X[a]["sp"]) - np.log(X[b]["sp"]))[both]
            p = dict(n=int(both.sum()), d_gap=float(dg.mean()), d_gap_ci=boot_ci(dg), d_log=float(dl.mean()), d_log_ci=boot_ci(dl))
            out["test"]["by_lp_gap"][f"pipeline - LP pipeline @ 0.5%, {nm_}"] = p
            L.append(f"\nPipeline − LP pipeline at 0.5 %, {nm_} (n = {p['n']}): Δ gap {p['d_gap']:+.3f} pp "
                     f"[{p['d_gap_ci'][0]:+.3f}, {p['d_gap_ci'][1]:+.3f}], Δ log speed-up {p['d_log']:+.2f} "
                     f"[{p['d_log_ci'][0]:+.2f}, {p['d_log_ci'][1]:+.2f}].")
    return L


