"""hard benchmark: tables for results/hard/hard_results.{md,json}.

    python scripts/uc_hard_report.py

Inputs: data/generated/hard/{val,test}_<kk>.npz (+ traces), results/hard/hard_eval_s*.jsonl (scripts/uc_hard_eval.py),
hard_tune_*.json, hard_train.json, hard_screen.json, data/generated/hard/pilot.json and polish_*.npz.

Paper metrics (Learning to Fix, Sec. IV-C): feasibility; over feasible instances the gap (C - DB) / C to the dual bound
DB of the re-timed full MILP at 0.1 % (the same DB for every row), the per-instance speed-up T_ref / T_method with
T_ref = that full MILP's time in the same process (mean [95 % CI], median, geometric mean, ratio of mean times), fixed
share after guards, served share (no shedding, over-generation or reserve shortfall). Time to the same quality: the
first time the reference full MILP's incumbent log reaches the method's cost, divided by the method's time (median and
geometric mean; capped at T_ref when the full MILP never reaches it). Paired comparisons: per-instance differences
(gap in pp, log speed-up), instance bootstrap 95 % CIs (2,000 resamples, seed 0).
"""
