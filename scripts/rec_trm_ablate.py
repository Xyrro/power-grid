"""Ablation table of the TRM study on a common footing (validation only).

    python3 scripts/rec_trm_ablate.py

For every validated model: the probability quality at its default step (BCE against its own targets, count-aware
wrong unit-hours), and the repaired 1-LP pipeline restricted to the quick decoder grid used by every ablation run
(viterbi at 0.2 / 0.3 / 0.5, blend0.5 at 0.3 / 0.5; lowest mean gap), plus the mixed screening (model schedule + 4 LP
roundings + repair). Output: results/recursive/trm_ablations.{md,json}.
"""
import glob
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(os.path.dirname(HERE), "results", "recursive")
QUICK = [("viterbi", 0.2), ("viterbi", 0.3), ("viterbi", 0.5), ("blend0.5", 0.3), ("blend0.5", 0.5)]
ORDER = ["main", "oneshot", "deep", "oneshot_long", "nods", "n2T1", "main_act", "main_rl", "oneshot_rl", "nolp",
         "oneshot_nolp", "y0lp", "oneshot_rank", "oneshot_costw", "oneshot_attn", "m1x"]
WHAT = {"main": "TRM (n 4, T 2, N_sup 8)", "oneshot": "one-shot, same net", "deep": "deep non-recursive, 10 nets",
        "oneshot_long": "one-shot, 18k steps (= TRM wall-clock)", "nods": "TRM without deep supervision (N_sup 1)",
        "n2T1": "TRM n 2, T 1", "main_act": "TRM, ACT at <= 8 wrong", "main_rl": "TRM + REINFORCE",
        "oneshot_rl": "one-shot + REINFORCE", "nolp": "TRM without LP features", "oneshot_nolp": "one-shot without LP features",
        "y0lp": "TRM, y initialised from the LP relaxation", "oneshot_rank": "one-shot, rank feature + canonical labels",
        "oneshot_costw": "one-shot, cost-weighted BCE", "oneshot_attn": "one-shot, axial attention mixers",
        "m1x": "m1x temporal-GNN ensemble"}


def main():
    vals = {os.path.basename(f)[8:-5]: json.load(open(f)) for f in glob.glob(os.path.join(RES, "trm_val_*.json"))}
    rows, out = [], {}
    for tag in ORDER:
        if tag not in vals:
            continue
        v = vals[tag]
        s, R = v["selection"], v["rows"]
        kd = s["rep"]["k_def"]
        cands = {c: R.get(f"{c[0]}|{c[1]}|k{kd}|rep") for c in QUICK}
        cands = {c: r for c, r in cands.items() if r}
        best = min(cands, key=lambda c: cands[c]["gap_mean"]) if cands else None
        pm = v.get("prob", {}).get(str(kd), {})
        p1 = v.get("prob", {}).get("1", {})
        mix = s["rep"].get("mix_metrics")
        curve = s.get("curve")
        rec = dict(tag=tag, what=WHAT.get(tag, tag), params=v.get("params"), k=kd, bce=pm.get("bce"), wrong=pm.get("wrong"),
                   bce_k1=p1.get("bce"), one_lp=cands.get(best), one_lp_cfg=best, mix=mix,
                   curve={k: c["rep"]["gap_mean"] for k, c in curve.items()} if curve else None,
                   bce_by_step={k: x["bce"] for k, x in v.get("prob", {}).items()} if v.get("cfg", {}).get("mode") == "trm" else None)
        out[tag] = rec
        f = lambda r: f"{r['gap_mean']:.2f} / {r['gap_median']:.2f} % ({r['served']:.0f} %)" if r else "–"
        bce = f"{rec['bce']:.4f}" if rec["bce"] is not None else "–"
        bk = (f"{rec['bce_k1']:.4f} → {rec['bce']:.4f}" if rec["bce_by_step"] else bce)
        b32 = f"{v['prob']['32']['bce']:.4f}" if rec["bce_by_step"] else "–"
        rows.append(f"| {rec['what']} (`{tag}`) | {rec['params'] or '–'} | {bk} | {b32} | "
                    f"{rec['wrong']:.1f} | {f(rec['one_lp'])} | {f(mix)} |" if rec["wrong"] is not None else
                    f"| {rec['what']} (`{tag}`) | – | – | – | – | {f(rec['one_lp'])} | {f(mix)} |")
    lines = ["# TRM study: ablations (validation, 360 instances)", "",
             "Generated by `scripts/rec_trm_ablate.py`. BCE against each model's own targets at k = 1 → its training step "
             "count (and at 32 steps for recursive models); wrong = count-aware wrong unit-hours per instance; 1 LP + repair "
             "restricted to the quick decoder grid (viterbi 0.2 / 0.3 / 0.5, blend0.5 0.3 / 0.5); mixed = the model's "
             "selected schedule + 4 LP roundings + repair. Mean / median gap to the stored MILP objective (served).", "",
             "| model | params | BCE (k = 1 → k_def) | BCE @32 | wrong | 1 LP + repair | + 4 LP roundings + repair |",
             "|---|---|---|---|---|---|---|"] + rows
    with open(os.path.join(RES, "trm_ablations.md"), "w") as fh:
        fh.write("\n".join(lines) + "\n")
    with open(os.path.join(RES, "trm_ablations.json"), "w") as fh:
        json.dump(out, fh, indent=1, default=float)
    print("\n".join(lines))


if __name__ == "__main__":
    main()
