"""Screening summary (results/hard/hard_screen.jsonl) -> results/hard/hard_screen.{md,json}.

    python scripts/uc_hard_screen_report.py
"""
import json
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
IN, OUT = "results/hard/hard_screen.jsonl", "results/hard/hard_screen"
ORDER = ["rts24_ls1_rf0.03", "rts24_ls0.8_rf0.03", "rts24_ls0.7_rf0.03", "rts24_ls0.6_rf0.03", "rts24_ls1_rf0.06",
         "rts24_ls1_rf0.1", "rts48_ls1_rf0.03", "rts12_ls1_rf0.03", "rts12_ls0.6_rf0.03", "ferc24"]
NAMES = {"rts24_ls1_rf0.03": "RTS-GMLC 24 h, original ratings, reserve 3 %",
         "rts24_ls0.8_rf0.03": "RTS-GMLC 24 h, ratings x 0.8", "rts24_ls0.7_rf0.03": "RTS-GMLC 24 h, ratings x 0.7",
         "rts24_ls0.6_rf0.03": "RTS-GMLC 24 h, ratings x 0.6", "rts24_ls1_rf0.06": "RTS-GMLC 24 h, reserve 6 %",
         "rts24_ls1_rf0.1": "RTS-GMLC 24 h, reserve 10 %", "rts48_ls1_rf0.03": "RTS-GMLC 48 h (two days)",
         "rts12_ls1_rf0.03": "RTS-GMLC 12 h (random start), original ratings",
         "rts12_ls0.6_rf0.03": "RTS-GMLC 12 h (random start), ratings x 0.6",
         "ferc24": "PGLib-UC FERC, first 24 h"}


def summary(rs):
    f = lambda k: np.array([r.get(k, np.nan) if r.get(k) is not None else np.nan for r in rs], float)
    ok = np.array(["lp_gap_obj" in r for r in rs])
    rs_ok = [r for r, o in zip(rs, ok) if o]
    g = lambda k: np.array([r[k] if r.get(k) is not None else np.nan for r in rs_ok], float)
    out = dict(n=len(rs), n_milp=int(ok.sum()))
    if not rs_ok:
        return out
    for k in ("lp_gap_obj", "lp_gap_db"):
        x = g(k)
        out[k] = dict(median=float(np.median(x)), mean=float(x.mean()), max=float(x.max()))
    out["int_share_%"] = float(g("int_share").mean() * 100)
    out["n_frac_mean"] = float(g("n_frac").mean())
    out["n_wrong_mean"] = float(g("n_wrong").mean())
    out["n_wrong_list"] = [int(x) for x in g("n_wrong")]
    out["decisions"] = int(rs_ok[0]["G"] * rs_ok[0]["T"])
    t = f("milp_time")
    out["milp_time"] = dict(median=float(np.median(t)), mean=float(np.mean(t)), min=float(np.min(t)), max=float(np.max(t)))
    out["n_time_limit"] = int(sum(r.get("milp_status") != "optimal" for r in rs))
    out["mip_gap_final_max_%"] = float(np.nanmax(g("mip_gap")) * 100)
    out["t_gap_1_median"] = float(np.nanmedian(g("t_gap_1"))) if np.isfinite(g("t_gap_1")).any() else None
    out["t_gap_0.5_median"] = float(np.nanmedian(g("t_gap_0.5"))) if np.isfinite(g("t_gap_0.5")).any() else None
    out["maxrss_mb"] = float(np.nanmax(f("maxrss_mb")))
    out["served_min_%"] = float(np.nanmin(g("served")) * 100)
    out["short_max"] = float(np.nanmax(g("short")))
    out["t_rel_mean"] = float(np.nanmean(f("t_rel")))
    if rs_ok[0]["bench"] == "rts":
        out["bind_share_%"] = float(g("bind_share").mean() * 100)
        out["n_lines_bind_mean"] = float(g("n_lines_bind").mean())
        out["above_orig_%"] = {k: float(g(f"above_{k}").mean() * 100) for k in ("1", "0.8", "0.7", "0.6")}
    return out


def main():
    os.chdir(os.path.dirname(HERE))
    recs = [json.loads(line) for line in open(IN)]
    cases = {}
    for r in recs:
        cases.setdefault(r["case"], []).append(r)
    res = {c: summary(cases[c]) for c in ORDER if c in cases}
    res["ferc24_per_file"] = {r["idx"]: dict(lp_gap_obj=r.get("lp_gap_obj"), lp_gap_db=r.get("lp_gap_db"),
                                             int_share=r.get("int_share"), n_frac=r.get("n_frac"), n_wrong=r.get("n_wrong"),
                                             milp_time=r.get("milp_time"), status=r.get("milp_status"),
                                             maxrss_mb=r.get("maxrss_mb")) for r in cases.get("ferc24", [])}
    json.dump(res, open(OUT + ".json", "w"), indent=1)
    L = ["# hard: screening of candidate benchmarks", "",
         "Generated by `scripts/uc_hard_screen_report.py` from `results/hard/hard_screen.jsonl` (`scripts/uc_hard_screen.py`). "
         "Per instance: LP relaxation, full MILP (HiGHS 1.15 via highspy, one thread, mip_rel_gap 0.1 %, time limit 300 s for "
         "RTS-GMLC 24 h, 600 s for FERC and RTS-GMLC 48 h). RTS-GMLC instances: the same 4 training-day scenarios "
         "(otsl.b3.make_jobs seed 777) in every 24 h setting (3 for the reserve settings, 1 for 48 h: the second was stopped); "
         "12 h: 6 training-day windows with random start (same seed). LP gap = (C − LP) / C to the "
         "MILP objective C and (DB − LP) / DB to its dual bound DB. Wrong integral values: relaxation values within 1e-6 of "
         "0 or 1 that disagree with the MILP schedule (aligned over identical units). Line loading: dispatch LP of the MILP "
         "schedule; binding = |f| ≥ 0.999 × rating of the setting; 'above k' = line-hours loaded ≥ k × the original rating.",
         "",
         "| setting | n | LP gap to C: median / mean / max % | to DB: median / mean / max % | integral % | fractional / inst. | "
         "wrong integral / inst. | MILP s: median / mean / max | at limit | peak RSS MB | served min % | reserve short max |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for c in ORDER:
        s = res.get(c)
        if not s or "lp_gap_obj" not in s:
            continue
        a, b, t = s["lp_gap_obj"], s["lp_gap_db"], s["milp_time"]
        L.append(f"| {NAMES[c]} | {s['n']} | {a['median']:.2f} / {a['mean']:.2f} / {a['max']:.2f} | {b['median']:.2f} / "
                 f"{b['mean']:.2f} / {b['max']:.2f} | {s['int_share_%']:.1f} | {s['n_frac_mean']:.0f} of {s['decisions']} | "
                 f"{s['n_wrong_mean']:.0f} | {t['median']:.0f} / {t['mean']:.0f} / {t['max']:.0f} | {s['n_time_limit']} | "
                 f"{s['maxrss_mb']:.0f} | {s['served_min_%']:.2f} | {s['short_max']:.3f} |")
    L += ["", "Line loading (RTS-GMLC): share of line-hours at the setting's rating, lines binding at least once, and share of "
          "line-hours loaded at or above k × the original rating.", "",
          "| setting | binding % | lines binding | ≥ 1.0 × orig % | ≥ 0.8 × | ≥ 0.7 × | ≥ 0.6 × |", "|---|---|---|---|---|---|---|"]
    for c in ORDER:
        s = res.get(c)
        if not s or "bind_share_%" not in s:
            continue
        ab = s["above_orig_%"]
        L.append(f"| {NAMES[c]} | {s['bind_share_%']:.2f} | {s['n_lines_bind_mean']:.1f} | {ab['1']:.2f} | {ab['0.8']:.2f} | "
                 f"{ab['0.7']:.2f} | {ab['0.6']:.2f} |")
    if res["ferc24_per_file"]:
        L += ["", "FERC per file (934 units, 872 free in the winter fleet, 842 in the Apr–Sep fleet; hw / lw = high / low wind):",
              "", "| file | LP gap to C % | to DB % | integral % | fractional | wrong integral | MILP s | status | peak RSS MB |",
              "|---|---|---|---|---|---|---|---|---|"]
        for k, r in res["ferc24_per_file"].items():
            if r["lp_gap_obj"] is None:
                continue
            L.append(f"| {k} | {r['lp_gap_obj']:.3f} | {r['lp_gap_db']:.3f} | {r['int_share'] * 100:.2f} | {r['n_frac']} | "
                     f"{r['n_wrong']} | {r['milp_time']:.0f} | {r['status']} | {r['maxrss_mb']:.0f} |")
    open(OUT + ".md", "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    sys.exit(main())
