"""Round 8 on PGLib-UC California (docs/methods/agg.md): report of scripts/agg_pglib_eval.py records (30 perturbed test
instances, 24 h) and of scripts/agg_pglib_base.py records (the 20 instances as distributed, 48 h).

    python3 scripts/agg_pglib_report.py                     # results/agg/pglib/*.jsonl -> results/agg/pglib/report.{md,json}
    python3 scripts/agg_pglib_report.py --base              # results/agg/pglib_base/*.jsonl -> results/agg/pglib_base/report.{md,json}

Gap: (C - DB) / C with DB the tightest bound of the instance's own runs (full MILPs' dual bounds, the certificates'
bounds, the LP relaxation). Speed-ups over the full MILP at 0.1 % solved in the same process: geometric mean, median,
mean of per-instance ratios (the paper's metric) and ratio of mean times. Paired comparisons with 95 % bootstrap
intervals over instances.
"""
import glob
import json
import math
import os

import numpy as np

RES = "results/agg/pglib"
NAMES = {"full@0.1%": "Full MILP, 0.1 % gap (reference)", "full@0.5%": "Full MILP, 0.5 % gap",
         "ltf_knn_1": "Learning to Fix (kNN, ε = 1 %, as published)"}


def label(n):
    if n in NAMES:
        return NAMES[n]
    if n.startswith("pcert:"):
        pred, d, e = n.split(":")[1:]
        first = ", rounded candidates first" if pred.startswith("r") else ""
        src = {"lp": "LP values, no learning", "knn": "kNN (Learning to Fix's predictor)", "st": "self-trained model"}[pred.lstrip("r")]
        return f"Certified pipeline, {src}{first}, δ = {d}, proven within {e} %"
    return n


def main():
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("--base", action="store_true", help="the 20 California instances as distributed (48 h)")
    a = ap.parse_args()
    os.chdir(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    global RES
    if a.base:
        RES = "results/agg/pglib_base"
    R = {}
    for f in sorted(glob.glob(os.path.join(RES, "*.jsonl"))):
        for line in open(f):
            r = json.loads(line)
            if a.base:
                r["k"] = r["file"]
            R[r["k"]] = r
    R = [R[k] for k in sorted(R)]
    if not R:
        raise SystemExit("no records")
    db = {}
    for r in R:
        b = [r["c_rel"]] + [v[x] for v in r["runs"].values() for x in ("bound", "cert_bound") if v.get(x) is not None
                            and np.isfinite(v[x])]
        db[r["k"]] = max(b)
    names = sorted({n for r in R for n in r["runs"]}, key=lambda n: (n not in NAMES, n))
    rng = np.random.default_rng(0)
    rows, out = [], dict(n=len(R), rows={}, paired=[])
    for n in names:
        rr = [r for r in R if n in r["runs"] and "full@0.1%" in r["runs"]]
        g = np.array([(r["runs"][n]["cost"] - db[r["k"]]) / r["runs"][n]["cost"] * 100 for r in rr])
        t = np.array([r["runs"][n]["time"] for r in rr])
        tref = np.array([r["runs"]["full@0.1%"]["time"] for r in rr])
        sp = tref / t
        x = dict(n=len(rr), gap_mean=g.mean(), gap_max=g.max(), served=100 * np.mean([r["runs"][n]["served"] for r in rr]),
                 time_mean=t.mean(), sp_geo=math.exp(np.log(sp).mean()), sp_median=float(np.median(sp)), sp_mean=sp.mean(),
                 ratio_of_means=tref.mean() / t.mean())
        if n.startswith("pcert:"):
            x["by_lp"] = sum(r["runs"][n]["cert"] in ("lp", "round") for r in rr)
            x["by_round"] = sum(r["runs"][n]["cert"] == "round" for r in rr)
            x["fixed"] = float(np.mean([r["runs"][n]["n_fixed"] for r in rr]))
        if n == "ltf_knn_1":
            x["fallbacks"] = sum(bool(r["runs"][n].get("fallback")) for r in rr)
        out["rows"][n] = x
        rows.append((n, x))
    head = ("# Round 8 on the PGLib-UC California instances as distributed (48 h, 410 free units)",
            f"Generated by `scripts/agg_pglib_report.py --base` from `{RES}/`. The {len(R)} instances of `ca/` unchanged; "
            "learning-free methods only (nothing trained or tuned on them)") if a.base else (
            "# Round 8 on PGLib-UC California (24 h, 410 free units): test",
            f"Generated by `scripts/agg_pglib_report.py` from `{RES}/`. {len(R)} test instances (seed 3 of "
            "`docs/methods/pglib.md`)")
    tl_hit = sum(r["runs"].get("full@0.1%", {}).get("status") == "Time limit reached" for r in R)
    L = [head[0], "", head[1] + "; every method of an instance ran back to back in one single-threaded process; gap to "
         "the tightest bound of the instance's own runs; speed-ups over that process's full MILP at 0.1 %"
         + (f" ({tl_hit} of them stopped at the time limit, so their speed-ups are lower bounds)" if tl_hit else "") + ".", "",
         "| method | gap mean % | gap max % | served | time s (mean) | speed-up geo / median / mean of ratios / ratio of means | proven by the LP bound |",
         "|---|---|---|---|---|---|---|"]
    for n, x in rows:
        extra = (f"{x['by_lp']} of {x['n']}" + (f" ({x['by_round']} at the rounding)" if x.get("by_round") else "")) if "by_lp" in x else (f"{x['fallbacks']} fallbacks" if "fallbacks" in x else "–")
        L.append(f"| {label(n)} | {x['gap_mean']:.3f} | {x['gap_max']:.2f} | {x['served']:.0f} % | {x['time_mean']:.1f} | "
                 f"{x['sp_geo']:.1f}× / {x['sp_median']:.1f}× / {x['sp_mean']:.1f}× / {x['ratio_of_means']:.1f}× | {extra} |")
    L += ["", "## Paired comparisons", "",
          "A's gap minus B's (pp) and A's speed-up over B (geometric mean), 95 % bootstrap intervals over instances.", "",
          "| A | B | instances | A − B, pp [95 % CI] | speed-up A over B [95 % CI] |", "|---|---|---|---|---|"]
    certs = [n for n in names if n.startswith("pcert:")]
    for na in certs:
        for nb in ("ltf_knn_1", "full@0.5%", "full@0.1%"):
            rr = [r for r in R if na in r["runs"] and nb in r["runs"]]
            if len(rr) < 3:
                continue
            d = np.array([((r["runs"][na]["cost"] - db[r["k"]]) / r["runs"][na]["cost"]
                           - (r["runs"][nb]["cost"] - db[r["k"]]) / r["runs"][nb]["cost"]) * 100 for r in rr])
            s = np.log([r["runs"][nb]["time"] / r["runs"][na]["time"] for r in rr])
            bd = [rng.choice(d, len(d)).mean() for _ in range(2000)]
            bs = [math.exp(rng.choice(s, len(s)).mean()) for _ in range(2000)]
            p = dict(a=na, b=nb, n=len(rr), diff=d.mean(), diff_ci=[np.percentile(bd, 2.5), np.percentile(bd, 97.5)],
                     speed=math.exp(s.mean()), speed_ci=[np.percentile(bs, 2.5), np.percentile(bs, 97.5)])
            out["paired"].append(p)
            L.append(f"| {label(na)} | {label(nb)} | {p['n']} | {p['diff']:+.3f} [{p['diff_ci'][0]:+.3f}, {p['diff_ci'][1]:+.3f}] | "
                     f"{p['speed']:.2f}× [{p['speed_ci'][0]:.2f}, {p['speed_ci'][1]:.2f}] |")
    hosts = sorted({(r.get("cpu_model"), r.get("highs")) for r in R})
    L += ["", f"Hardware: {hosts}."]
    open(os.path.join(RES, "report.md"), "w").write("\n".join(L) + "\n")
    json.dump(out, open(os.path.join(RES, "report.json"), "w"), indent=1, default=float)
    print("\n".join(L))


if __name__ == "__main__":
    main()
